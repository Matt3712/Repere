#!/usr/bin/env python3
"""Prepare a newly staged standalone runtime; never edits a host installation."""
import importlib.metadata
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys


def normalized(value):
    return re.sub(r"[-_.]+", "-", value).lower()


def main():
    resources = Path(sys.argv[1]).resolve()
    runtime = resources / "runtime"
    assert Path(sys.prefix).resolve() == runtime, "Run this script with the staged interpreter"
    expected = {}
    for line in Path(sys.argv[2]).read_text().splitlines():
        if line.strip() and not line.startswith("#"):
            name, version = line.strip().split("==", 1)
            expected[normalized(name)] = version
    installed = {normalized(d.metadata["Name"]): d for d in importlib.metadata.distributions()}
    for name, version in expected.items():
        assert name in installed and installed[name].version == version, f"Dependency mismatch: {name}=={version}"
    inventory = []
    for name, dist in sorted(installed.items()):
        destination = resources / "Licenses" / name
        destination.mkdir(parents=True, exist_ok=True)
        copied = []
        for entry in dist.files or []:
            parts = Path(str(entry)).parts
            basename = parts[-1].lower()
            if not (basename.startswith(("license", "licence", "copying", "notice", "authors"))
                    or "licenses" in (part.lower() for part in parts)):
                continue
            source = Path(dist.locate_file(entry)).resolve()
            if not source.is_file() or not source.is_relative_to(runtime):
                continue
            target = destination / source.relative_to(runtime)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, target)
            copied.append(str(target.relative_to(resources)))
        metadata = dist.read_text("METADATA") or ""
        (destination / "METADATA.txt").write_text(metadata)
        supplement = Path(__file__).with_name("ThirdPartyLicenses") / name
        if supplement.is_dir():
            provenance = json.loads((supplement / "PROVENANCE.json").read_text())
            assert provenance["version"] == dist.version, f"License supplement version mismatch: {name}"
            assert hashlib.sha256((supplement / "LICENSE.txt").read_bytes()).hexdigest() == provenance["license_sha256"], f"License checksum mismatch: {name}"
            for source in supplement.iterdir():
                if source.is_file():
                    target = destination / source.name
                    shutil.copy2(source, target)
                    copied.append(str(target.relative_to(resources)))
        inventory.append({"name": dist.metadata["Name"], "version": dist.version,
                          "license": dist.metadata.get("License-Expression") or dist.metadata.get("License"),
                          "license_files": copied})
    (resources / "Licenses" / "DEPENDENCIES.json").write_text(json.dumps(inventory, ensure_ascii=False, indent=2) + "\n")

    # Console scripts generated by pip have absolute staging-directory shebangs.
    # Repère launches modules through its interpreter and does not need them.
    for item in (runtime / "bin").iterdir():
        if item.name not in {"python", "python3", "python3.14"}:
            if item.is_dir() and not item.is_symlink():
                shutil.rmtree(item)
            else:
                item.unlink()

    # Some published wheels retain unused build-machine LC_RPATH entries (for
    # example Pillow's /Users/runner/.../build/deps/darwin/lib). Remove these
    # before signing. Actual external load dependencies are NOT rewritten and
    # remain a fatal error in verify_bundle.py.
    magic = {b"\xfe\xed\xfa\xce", b"\xce\xfa\xed\xfe", b"\xfe\xed\xfa\xcf", b"\xcf\xfa\xed\xfe",
             b"\xca\xfe\xba\xbe", b"\xbe\xba\xfe\xca", b"\xca\xfe\xba\xbf", b"\xbf\xba\xfe\xca"}
    removed = []
    for item in runtime.rglob("*"):
        if item.is_symlink() or not item.is_file():
            continue
        with item.open("rb") as stream:
            if stream.read(4) not in magic:
                continue
        commands = subprocess.check_output(["/usr/bin/otool", "-l", str(item)], text=True)
        rpaths = re.findall(r"cmd LC_RPATH\s+cmdsize \d+\s+path (.*?) \(offset \d+\)", commands)
        for rpath in sorted(set(rpaths)):
            if rpath.startswith("/") and not rpath.startswith(("/usr/lib/", "/System/Library/")):
                subprocess.run(["/usr/bin/install_name_tool", "-delete_rpath", rpath, str(item)],
                               check=True, capture_output=True, text=True)
                removed.append({"binary": str(item.relative_to(runtime)), "rpath": rpath})
    (resources / "runtime-adjustments.json").write_text(json.dumps({"removed_build_rpaths": removed}, indent=2) + "\n")
    print(f"Dépendances verrouillées vérifiées : {len(expected)} ; licences recensées : {len(inventory)}.")
    print(f"Chemins de recherche de compilation retirés : {len(removed)}.")


if __name__ == "__main__":
    main()
